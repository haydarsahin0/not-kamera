"""Build checked-in monochrome Unicode glyphs from DejaVu Sans Bold.

Requires Pillow and fontTools. The firmware uses the generated header directly;
rebuilding the firmware does not require regenerating the font.
"""
import argparse
from pathlib import Path
import unicodedata
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--font', default='/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf')
args = parser.parse_args()
source = TTFont(args.font)
cmap = source.getBestCmap()
# Latin, combining marks, Greek, punctuation, superscripts/subscripts,
# currency, arrows and mathematics. Include only real glyphs (never .notdef).
ranges = [(0x20, 0x24f), (0x300, 0x3ff), (0x2000, 0x23ff)]
points = sorted(cp for lo, hi in ranges for cp in range(lo, hi + 1)
                if cp in cmap and unicodedata.category(chr(cp)) not in ('Cc', 'Cf', 'Cn'))
out = ['// Generated by firmware/tools/prepare_font.py; DejaVu license in FONT-LICENSE.txt.',
       '#pragma once', '#include <stdint.h>', '#include <stddef.h>',
       'namespace NoteFont {',
       'struct Glyph { uint32_t code, offset; uint8_t width, height, advance; int8_t left, top; };',
       'struct Font { const Glyph *glyphs; size_t count; const uint8_t *bitmap; uint8_t pixels, lineHeight, ascent; };']
for size in (16, 18):
    font = ImageFont.truetype(args.font, size)
    glyphs, bitmap = [], bytearray()
    for cp in points:
        char = chr(cp)
        left, top, right, bottom = font.getbbox(char, anchor='ls')
        width, height = right - left, bottom - top
        advance = round(font.getlength(char))
        assert width <= 192 and -128 <= left <= 127 and -128 <= top <= 127
        raster = Image.new('L', (max(1, width), max(1, height)))
        ImageDraw.Draw(raster).text((-left, -top), char, font=font, fill=255, anchor='ls')
        packed = bytearray((width * height + 7) // 8)
        for y in range(height):
            for x in range(width):
                if raster.getpixel((x, y)) >= 96:
                    bit = y * width + x
                    packed[bit // 8] |= 0x80 >> (bit % 8)
        glyphs.append((cp, len(bitmap), width, height, advance, left, top))
        bitmap.extend(packed)
    out.append(f'static const uint8_t bitmap{size}[] = {{')
    out.extend(','.join(f'0x{b:02x}' for b in bitmap[i:i+24])+',' for i in range(0, len(bitmap), 24))
    out.append('};')
    out.append(f'static const Glyph glyphs{size}[] = {{')
    out.extend('{' + ','.join(map(str, g)) + '},' for g in glyphs)
    out.append('};')
    out.append(f'static const Font font{size} = {{glyphs{size}, sizeof(glyphs{size})/sizeof(Glyph), bitmap{size}, {size}, {size+6}, {font.getmetrics()[0]}}};')
out.append('struct Composition { uint32_t base, mark, composed; };')
compositions = []
for cp in points:
    decomposed = unicodedata.normalize('NFD', chr(cp))
    if len(decomposed) == 2 and unicodedata.combining(decomposed[1]):
        compositions.append((ord(decomposed[0]), ord(decomposed[1]), cp))
out.append('static const Composition compositions[] = {')
out.extend('{' + ','.join(map(str, g)) + '},' for g in sorted(compositions))
out += ['};', '} // namespace NoteFont']
(root / 'NotEkran' / 'unicode_font_data.h').write_text('\n'.join(out)+'\n')
print(f'Generated {len(points)} supported Unicode characters in 16px and 18px fonts')
